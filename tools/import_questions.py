"""Convert the supplied Word question bank to a WeChat Mini Program module."""

import argparse
import json
import re
import unicodedata
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

WORD = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
LESSON_NAMES = (
    "一 二 三 四 五 六 七 八 九 十 十一 十二 十三 十四 十五 十六 十七 十八 十九 二十"
).split()
LESSON_IDS = {f"第{name}课": f"{i:02}" for i, name in enumerate(LESSON_NAMES, 1)}
QUESTION_TYPE = re.compile(r"[（(](单选|多选)[）)]\s*$")
QUESTION_NUMBER = re.compile(r"^(\d+)[.．、]\s*")
PARENTHESIZED_KEY = re.compile(r"[（(]\s*([A-DＡ-Ｄ](?:\s*[A-DＡ-Ｄ])*)\s*[）)]")
UNDERSCORED_KEY = re.compile(r"_+([A-DＡ-Ｄ]+)_+")
TRAILING_KEY = re.compile(r"(?<![A-Za-z])([A-DＡ-Ｄ]+)\s*$")
OPTION_LABEL = re.compile(r"^([A-DＡ-Ｄ])[.．、)]\s*")


def read_paragraphs(path):
    with zipfile.ZipFile(path) as document:
        root = ET.fromstring(document.read("word/document.xml"))
    return [
        text
        for paragraph in root.findall(f"./{WORD}body/{WORD}p")
        if (text := "".join(node.text or "" for node in paragraph.iter(f"{WORD}t")).strip())
    ]


def new_lesson(label):
    return {"id": LESSON_IDS[label], "label": label, "questions": []}


def extract_question(stem, options, question_id, number):
    question_type = QUESTION_TYPE.search(stem)
    if question_type is None or len(options) != 4:
        raise ValueError(f"{question_id}: expected a question type and four options")
    stem = stem[:question_type.start()].rstrip()
    printed_number = QUESTION_NUMBER.match(stem)
    if printed_number:
        if int(printed_number[1]) != number:
            raise ValueError(f"{question_id}: unexpected question number {printed_number[1]}")
        stem = stem[printed_number.end():]

    keys = set()
    for pattern, replacement in (
        (PARENTHESIZED_KEY, "（　）"),
        (UNDERSCORED_KEY, "____"),
        (TRAILING_KEY, ""),
    ):
        for answer in pattern.findall(stem):
            keys.update(unicodedata.normalize("NFKC", "".join(answer.split())))
        stem = pattern.sub(replacement, stem)

    question_type = "single" if question_type[1] == "单选" else "multiple"
    if not keys or (len(keys) == 1) != (question_type == "single"):
        raise ValueError(f"{question_id}: answer does not match the question type")

    option_texts = []
    for letter, text in zip("ABCD", options):
        label = OPTION_LABEL.match(text)
        if label:
            if unicodedata.normalize("NFKC", label[1]) != letter:
                raise ValueError(f"{question_id}: option {letter} is out of order")
            text = text[label.end():]
        option_texts.append(text)

    if not stem.strip() or not all(option_texts):
        raise ValueError(f"{question_id}: blank question or option")
    return {
        "id": question_id,
        "type": question_type,
        "stem": stem.strip(),
        "options": option_texts,
        "answer": "".join(sorted(keys)),
    }


def parse_lessons(paragraphs):
    lessons = [new_lesson("第一课")]
    cursor = 0
    while cursor < len(paragraphs):
        line = paragraphs[cursor]
        if line in LESSON_IDS:
            if lessons[-1]["questions"]:
                lessons.append(new_lesson(line))
            else:
                lessons[-1] = new_lesson(line)
            cursor += 1
            continue

        lesson = lessons[-1]
        number = len(lesson["questions"]) + 1
        question_id = f"{lesson['id']}-{number:02}"
        stem = line
        cursor += 1
        if not QUESTION_TYPE.search(stem) and cursor < len(paragraphs):
            stem += "\n" + paragraphs[cursor]
            cursor += 1
        options = paragraphs[cursor:cursor + 4]
        lesson["questions"].append(extract_question(stem, options, question_id, number))
        cursor += 4
    return lessons


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    lessons = parse_lessons(read_paragraphs(args.source))
    output = Path(__file__).resolve().parent.parent / "miniprogram/data/question-bank.js"
    output.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(lessons, ensure_ascii=False, indent=2)
    output.write_text(
        "// Generated by tools/import_questions.py.\nmodule.exports = " + serialized + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    total = sum(len(lesson["questions"]) for lesson in lessons)
    print(f"Imported {total} questions in {len(lessons)} lessons.")


if __name__ == "__main__":
    main()
